// @ts-check

/**
 * Hide the same-day delivery rate once the store's local time passes the
 * cutoff declared in src/run.graphql.
 *
 * Why a function and not a scheduled job. Shopify Functions are required to be
 * deterministic — the same input must give the same output, and results are
 * cached — so reading the clock inside the function with Date.now() is both
 * unsupported and unreliable. shop.localTime is how Shopify provides the time
 * properly: the comparison is made server-side, against the store's timezone,
 * and arrives as a plain boolean. Nothing here asks what time it is.
 *
 * Matching by title, not handle. A rate's handle is generated by Shopify and
 * changes if the rate is deleted and recreated — which is exactly what happens
 * when someone edits a shipping zone. The title is what the merchant typed and
 * what the customer reads, so it is the stable identifier in practice.
 */

const CUTOFF_LABEL = 'same-day';

/** @type {import("../generated/api").RunInput} */
/** @type {import("../generated/api").FunctionRunResult} */
const NO_CHANGES = { operations: [] };

export function run(input) {
  // False before the cutoff, true after it. Null if the field is absent, which
  // is treated as "not after" so a schema change fails open: the rate keeps
  // showing rather than silently disappearing all day.
  const past = input?.shop?.localTime?.timeAfter === true;
  if (!past) return NO_CHANGES;

  const groups = input?.cart?.deliveryGroups ?? [];
  const operations = [];

  for (const group of groups) {
    for (const option of group?.deliveryOptions ?? []) {
      const title = (option?.title ?? '').toLowerCase();
      if (!title.includes(CUTOFF_LABEL)) continue;
      if (!option?.handle) continue;
      operations.push({
        deliveryOptionHide: { deliveryOptionHandle: option.handle },
      });
    }
  }

  // Shopify rejects a result that hides every option, which would leave the
  // customer unable to check out at all. If same-day is somehow the only rate
  // in a group, leave it alone and let a human notice the configuration is
  // wrong — a blocked checkout is worse than a late same-day order.
  const total = groups.reduce((n, g) => n + (g?.deliveryOptions?.length ?? 0), 0);
  if (operations.length >= total) return NO_CHANGES;

  return { operations };
}
